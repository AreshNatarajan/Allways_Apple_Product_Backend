// controllers/sale/setSaleInvoiceFile.controller.js
import mongoose from "mongoose";
import Sale from "../../models/Sale.modal.js";
import { successResponse, errorResponse } from "../../utils/responseHandler.js";

// Persists the client-generated system invoice's S3 URL onto the sale -
// deliberately its own narrow endpoint rather than routed through
// PUT /sale/:id (updateSaleController), which recomputes payments/stock/
// EOD review and would be a much bigger blast radius for setting one
// field. Touches ONLY systemInvoiceFile (+ the regenerate-only audit
// pair below), nothing else - no review reset, no recompute, matching
// this project's existing narrow-endpoint convention (see
// reviewSaleController's equally narrow scope).
//
// First-time generation is still "invoiced exactly once" (same guard the
// old server-side generator used to enforce, generateSaleInvoicePdf.js,
// now removed) - a sale is never silently re-invoiced. The one deliberate
// exception is `regenerate: true`, sent ONLY from the Sale Detail page's
// own "Regenerate Invoice" action (see NotesCard.jsx) - staff explicitly
// picks one sale and asks for its invoice to be re-rendered against
// whatever the CURRENT Invoice.jsx template looks like today (e.g. after
// the template itself changed and older sales' stored PDFs are now
// stale). Without that flag, the original overwrite guard still applies
// unchanged.
export const setSaleInvoiceFileController = async (req, res) => {
    try {
        const { id } = req.params;
        const { systemInvoiceFile, regenerate } = req.body;
        const user = req.user;

        if (!mongoose.Types.ObjectId.isValid(id)) {
            return errorResponse(res, "Invalid sale ID", 400);
        }
        if (!systemInvoiceFile || typeof systemInvoiceFile !== "string") {
            return errorResponse(res, "A valid invoice URL is required", 400);
        }

        const sale = await Sale.findOne({ _id: id, isDeleted: false });
        if (!sale) {
            return errorResponse(res, "Sale not found", 404);
        }
        if (sale.systemInvoiceFile && !regenerate) {
            return errorResponse(res, "This sale already has a system invoice - it cannot be regenerated or overwritten.", 400);
        }

        sale.systemInvoiceFile = systemInvoiceFile;
        if (regenerate) {
            sale.systemInvoiceUpdatedBy = user._id;
            sale.systemInvoiceUpdatedAt = new Date();
        }
        await sale.save();

        return successResponse(res, regenerate ? "System invoice regenerated successfully" : "System invoice saved successfully", {
            _id: sale._id,
            systemInvoiceFile: sale.systemInvoiceFile,
            systemInvoiceUpdatedAt: sale.systemInvoiceUpdatedAt,
            // Inline, not populated from the DB - the caller already IS
            // this user, so there's no need for a follow-up query just to
            // show "regenerated by <name>" immediately in the UI.
            systemInvoiceUpdatedBy: regenerate ? { _id: user._id, name: user.name || "" } : sale.systemInvoiceUpdatedBy,
        });
    } catch (error) {
        console.error("Set Sale Invoice File Error:", error);
        return errorResponse(res, "Failed to save system invoice", 500);
    }
};
