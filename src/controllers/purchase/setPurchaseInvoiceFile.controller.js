// controllers/purchase/setPurchaseInvoiceFile.controller.js
import mongoose from "mongoose";
import Purchase from "../../models/Purchase.modal.js";
import { successResponse, errorResponse } from "../../utils/responseHandler.js";

// Persists the client-generated system invoice's S3 URL onto the
// purchase - exact mirror of Sale's setSaleInvoiceFile.controller.js.
// Touches ONLY systemInvoiceFile (+ the regenerate-only audit pair),
// nothing else.
//
// First-time generation is "invoiced exactly once" - a purchase is
// never silently re-invoiced. The one deliberate exception is
// `regenerate: true`, sent ONLY from Purchase Detail's own "Regenerate
// Invoice" action (PurchaseNotesView.jsx) - staff explicitly picks one
// purchase and asks for its invoice to be re-rendered against its
// current data (e.g. after editing the purchase). Without that flag,
// the original overwrite guard still applies unchanged.
export const setPurchaseInvoiceFileController = async (req, res) => {
    try {
        const { id } = req.params;
        const { systemInvoiceFile, regenerate } = req.body;
        const user = req.user;

        if (!mongoose.Types.ObjectId.isValid(id)) {
            return errorResponse(res, "Invalid purchase ID", 400);
        }
        if (!systemInvoiceFile || typeof systemInvoiceFile !== "string") {
            return errorResponse(res, "A valid invoice URL is required", 400);
        }

        const purchase = await Purchase.findOne({ _id: id, isDeleted: false });
        if (!purchase) {
            return errorResponse(res, "Purchase not found", 404);
        }
        if (purchase.systemInvoiceFile && !regenerate) {
            return errorResponse(res, "This purchase already has a system invoice - it cannot be regenerated or overwritten.", 400);
        }

        purchase.systemInvoiceFile = systemInvoiceFile;
        if (regenerate) {
            purchase.systemInvoiceUpdatedBy = user._id;
            purchase.systemInvoiceUpdatedAt = new Date();
        }
        await purchase.save();

        return successResponse(res, regenerate ? "System invoice regenerated successfully" : "System invoice saved successfully", {
            _id: purchase._id,
            systemInvoiceFile: purchase.systemInvoiceFile,
            systemInvoiceUpdatedAt: purchase.systemInvoiceUpdatedAt,
            // Inline, not populated from the DB - the caller already IS
            // this user, so there's no need for a follow-up query just to
            // show "regenerated by <name>" immediately in the UI.
            systemInvoiceUpdatedBy: regenerate ? { _id: user._id, name: user.name || "" } : purchase.systemInvoiceUpdatedBy,
        });
    } catch (error) {
        console.error("Set Purchase Invoice File Error:", error);
        return errorResponse(res, "Failed to save system invoice", 500);
    }
};
